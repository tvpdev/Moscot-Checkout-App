import type { HeadersFunction, LoaderFunctionArgs } from "react-router";
import { authenticate } from "../shopify.server";
import { boundary } from "@shopify/shopify-app-react-router/server";

export const loader = async ({ request }: LoaderFunctionArgs) => {
  await authenticate.admin(request);
  return null;
};

export default function Index() {
  return (
    <s-page>
      <ui-title-bar title="Moscot checkout" />
      <s-section heading="Welcome to moscot checkout">
        <s-paragraph>
          This app powers checkout extensions for Moscot, including SMS consent,
          shipping messaging, delivery customization, and order summary content.
        </s-paragraph>
      </s-section>
    </s-page>
  );
}

export const headers: HeadersFunction = (headersArgs) => {
  return boundary.headers(headersArgs);
};
